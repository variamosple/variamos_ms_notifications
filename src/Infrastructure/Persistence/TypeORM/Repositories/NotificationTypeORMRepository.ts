import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, Not, ObjectLiteral, Repository } from "typeorm";
import { Notification } from "../../../../Domain/Entities/Notification.js";
import { requireRecipient } from "../../../../Domain/Errors/NotificationErrors.js";
import { INotificationRepository } from "../../../../Domain/Repositories/INotificationRepository.js";
import { NotificationEntity } from "../Entities/NotificationEntity.js";
import * as NotificationMapper from "../Mappers/NotificationMapper.js";

@Injectable()
export class NotificationTypeORMRepository implements INotificationRepository {
  constructor(
    @InjectRepository(NotificationEntity)
    private readonly repository: Repository<NotificationEntity>,
  ) {}

  public async save(notification: Notification): Promise<Notification> {
    const entity = NotificationMapper.toPersistence(notification);
    const savedEntity = await this.repository.save(entity);
    return NotificationMapper.toDomain(savedEntity);
  }

  public async saveMany(
    notifications: Notification[],
  ): Promise<Notification[]> {
    if (notifications.length === 0) {
      return [];
    }
    const entities = notifications.map((n) =>
      NotificationMapper.toPersistence(n),
    );
    // New rows only: one INSERT, without the SELECT per row that save()
    // runs to tell an insert from an update (EV-101, OPT-04). TypeORM merges
    // the values generated by the database into the entities. The rows are
    // typed as plain objects: TypeScript cannot expand the insert type of the
    // recursive JSON columns (TS2589).
    if (entities.every((e) => e.eventId === null)) {
      await this.repository.manager
        .getRepository<ObjectLiteral>(NotificationEntity)
        .insert(entities);
      return entities.map((e) => NotificationMapper.toDomain(e));
    }
    // A send repeated with its key (EV-99): the recipients who already hold
    // a notification of that key are left out, in the same INSERT, so two
    // sends running at once cannot both save it. Only the rows inserted come
    // back. The ids are new random UUIDs, so the only conflict left to
    // ignore is the one on the key. updateEntity(false): TypeORM would copy
    // the rows returned into the entities by position, which no longer
    // match once a row is left out.
    const inserted = await this.repository.manager
      .createQueryBuilder()
      .insert()
      .into(NotificationEntity)
      .values(entities as ObjectLiteral[])
      .orIgnore()
      .returning(["id"])
      .updateEntity(false)
      .execute();
    const insertedIds = new Set(
      (inserted.raw as { id: string }[]).map((row) => row.id),
    );
    return entities
      .filter((e) => insertedIds.has(e.id))
      .map((e) => NotificationMapper.toDomain(e));
  }

  public async findById(id: string): Promise<Notification | null> {
    const entity = await this.repository.findOne({ where: { id } });
    if (!entity) {
      return null;
    }
    return NotificationMapper.toDomain(entity);
  }

  public async findByRecipient(
    recipientId: string,
    page: number,
    limit: number,
    folder: "inbox" | "trash",
  ): Promise<Notification[]> {
    // A query without recipient would read every user's notifications
    requireRecipient(recipientId);
    const entities = await this.repository.find({
      where: {
        recipientId,
        deletedAt: folder === "inbox" ? IsNull() : Not(IsNull()),
      },
      order: { createdAt: "DESC" },
      skip: (page - 1) * limit,
      take: limit,
    });
    return entities.map((e) => NotificationMapper.toDomain(e));
  }

  public async countUnread(recipientId: string): Promise<number> {
    requireRecipient(recipientId);
    return this.repository.count({
      where: {
        recipientId,
        isRead: false,
        deletedAt: IsNull(),
      },
    });
  }

  public async markAllAsRead(recipientId: string): Promise<void> {
    // TypeORM 0.3 dropped an undefined criterion, so the update could touch
    // every user's rows (CA-NT-01). TypeORM 1 throws instead; this check
    // keeps the domain error and its 400 answer
    requireRecipient(recipientId);
    await this.repository.update(
      { recipientId, isRead: false, deletedAt: IsNull() },
      { isRead: true, readAt: new Date() },
    );
  }

  public async emptyTrash(recipientId: string): Promise<void> {
    requireRecipient(recipientId);
    await this.repository.delete({
      recipientId,
      deletedAt: Not(IsNull()),
    });
  }
}
